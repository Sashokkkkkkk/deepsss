-- ============================================================
-- Запрос 1. Общее количество забронированных туров в страны Европы
-- ============================================================
SELECT COUNT(*) AS "Количество_броней_в_Европу"
FROM "Бронирование" b
JOIN "Туры" t ON b."Код_тура" = t."Код_тура"
JOIN "Страны" s ON t."Код_страны" = s."Код_страны"
WHERE s."Континент" = 'Европа'
  AND b."Статус" != 'отменено';


-- ============================================================
-- Запрос 2. Итоговая стоимость бронирования для каждой путевки
-- Формула: цена_за_день * количество_дней * (взрослые + дети * 0.7)
-- (скидка 30% на детей)
-- ============================================================
SELECT 
    b."Код_брони",
    t."Название" AS "Тур",
    s."Название" AS "Страна",
    t."Длительность_дней" AS "Дней",
    t."Цена_за_день",
    b."Взрослые",
    b."Дети",
    ROUND(t."Цена_за_день" * t."Длительность_дней" * (b."Взрослые" + b."Дети" * 0.7), 2) AS "Итоговая_стоимость"
FROM "Бронирование" b
JOIN "Туры" t ON b."Код_тура" = t."Код_тура"
JOIN "Страны" s ON t."Код_страны" = s."Код_страны"
ORDER BY b."Код_брони";


-- ============================================================
-- Запрос 3. Страны, в которые были проданы туры на ближайший месяц
-- (от текущей даты 2026-09-21, в течение 30 дней)
-- ============================================================
SELECT DISTINCT 
    s."Название" AS "Страна", 
    COUNT(*) AS "Количество_броней"
FROM "Бронирование" b
JOIN "Туры" t ON b."Код_тура" = t."Код_тура"
JOIN "Страны" s ON t."Код_страны" = s."Код_страны"
WHERE b."Дата_начала_тура" BETWEEN '2026-09-21' AND date('2026-09-21', '+30 days')
  AND b."Статус" != 'отменено'
GROUP BY s."Название"
ORDER BY "Количество_броней" DESC;


-- ============================================================
-- Запрос 4. Страны, где средняя стоимость тура на человека 
-- (с учётом дней) выше средней по всем турам фирмы,
-- но количество забронированных путёвок < 3
-- ============================================================
WITH tour_cost AS (
    SELECT 
        s."Код_страны",
        s."Название",
        t."Цена_за_день" * t."Длительность_дней" AS cost_per_person
    FROM "Туры" t
    JOIN "Страны" s ON t."Код_страны" = s."Код_страны"
),
avg_all AS (
    SELECT AVG(cost_per_person) AS avg_cost FROM tour_cost
),
country_avg AS (
    SELECT 
        "Код_страны",
        "Название",
        AVG(cost_per_person) AS avg_country_cost
    FROM tour_cost
    GROUP BY "Код_страны", "Название"
),
country_bookings AS (
    SELECT 
        s."Код_страны",
        COUNT(b."Код_брони") AS cnt
    FROM "Бронирование" b
    JOIN "Туры" t ON b."Код_тура" = t."Код_тура"
    JOIN "Страны" s ON t."Код_страны" = s."Код_страны"
    WHERE b."Статус" != 'отменено'
    GROUP BY s."Код_страны"
)
SELECT 
    ca."Название" AS "Страна",
    ROUND(ca.avg_country_cost, 2) AS "Средняя_стоимость_тура",
    ROUND((SELECT avg_cost FROM avg_all), 2) AS "Общая_средняя",
    COALESCE(cb.cnt, 0) AS "Количество_броней"
FROM country_avg ca
LEFT JOIN country_bookings cb ON ca."Код_страны" = cb."Код_страны"
WHERE ca.avg_country_cost > (SELECT avg_cost FROM avg_all)
  AND COALESCE(cb.cnt, 0) < 3
ORDER BY ca.avg_country_cost DESC;
